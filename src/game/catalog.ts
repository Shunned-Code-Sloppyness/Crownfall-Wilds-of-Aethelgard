let uidCounter = 1;
export function createItemInstance(
  templateId: string,
  qty = 1,
  rarityOverride?: Rarity,
): InventoryItem {
  const tpl = ITEM_TEMPLATES[templateId];
  if (!tpl) {
    throw new Error(`Unknown item template: ${templateId}`);
  }
  uidCounter += 1;
  return {
    uid: `itm_${Date.now().toString(36)}_${uidCounter}_${Math.random().toString(36).slice(2, 6)}`,
    templateId,
    qty,
    rarity: rarityOverride ?? tpl.rarity,
    durability: tpl.stackable ? undefined : 100,
  };
}

export function getEffectiveItemPower(item: InventoryItem): number {
  const tpl = ITEM_TEMPLATES[item.templateId];
  if (!tpl) return 0;
  const rarityMult = RARITY_META[item.rarity].mult;
  return Math.round((tpl.tier * 100 + (tpl.stats?.attack ?? 0) * 3 + (tpl.stats?.maxHp ?? 0)) * rarityMult);
}

export function rollDropRarity(baseTier: Tier, isBoss: boolean): Rarity {
  const r = Math.random();
  if (isBoss) {
    if (r < 0.16 && baseTier >= 4) return 'legendary';
    if (r < 0.52) return 'epic';
    return 'rare';
  }
  if (r < 0.03) return 'epic';
  if (r < 0.13) return 'rare';
  if (r < 0.38) return 'uncommon';
  return 'common';
}
