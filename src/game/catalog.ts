/**
 * Damage Type vs Armor Class effectiveness matrix.
 * Plate resists slashing/piercing but takes heavy crushing & arcane damage.
 * Leather is balanced with vulnerability to piercing.
 * Cloth resists arcane/magic but takes heavy slashing damage.
 */
export const DAMAGE_MATRIX: Record<DamageType, Record<ArmorClass, number>> = {
  slashing: { plate: 0.78, leather: 1.0, cloth: 1.28 },
  piercing: { plate: 0.82, leather: 1.22, cloth: 1.1 },
  crushing: { plate: 1.32, leather: 1.0, cloth: 0.92 },
  arcane: { plate: 1.26, leather: 1.04, cloth: 0.74 },
};

export function getDamageMultiplier(
  damageType: DamageType,
  targetArmor: ArmorClass,
): number {
  return DAMAGE_MATRIX[damageType][targetArmor];
}

export function getEffectivenessLabel(mult: number): 'STRONG' | 'RESISTED' | 'NORMAL' {
  if (mult >= 1.15) return 'STRONG';
  if (mult <= 0.85) return 'RESISTED';
  return 'NORMAL';
}

